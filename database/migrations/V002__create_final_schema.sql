-- 7. MATCH PERFORMANCE
--------------------------------------------------------------------------------

CREATE TABLE batting_performance (
    bat_stat_id      NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    bat_summary_id   NUMBER(10) NOT NULL,
    match_id         NUMBER(10) NOT NULL,
    runs_scored      NUMBER(10) NOT NULL,
    balls_faced      NUMBER(10) NOT NULL,
    strike_rate      NUMBER(7,2) NOT NULL,
    dismissal_type   VARCHAR2(50),

    CONSTRAINT pk_batting_performance PRIMARY KEY (bat_stat_id),
    CONSTRAINT fk_batting_performance_summary FOREIGN KEY (bat_summary_id)
        REFERENCES batting_summary(bat_summary_id),
    CONSTRAINT fk_batting_performance_match FOREIGN KEY (match_id)
        REFERENCES match(match_id),
    CONSTRAINT uq_batting_perf_match_summary UNIQUE (match_id, bat_summary_id),
    CONSTRAINT ck_batting_performance_values CHECK (
        runs_scored >= 0 AND
        balls_faced >= 0 AND
        strike_rate >= 0
    )
);

CREATE TABLE bowling_performance (
    bowl_stat_id     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    bowl_summary_id  NUMBER(10) NOT NULL,
    match_id         NUMBER(10) NOT NULL,
    wickets_taken    NUMBER(10) NOT NULL,
    balls_bowled     NUMBER(10) NOT NULL,
    runs_conceded    NUMBER(10) NOT NULL,
    economy_rate     NUMBER(7,2) NOT NULL,

    CONSTRAINT pk_bowling_performance PRIMARY KEY (bowl_stat_id),
    CONSTRAINT fk_bowling_performance_summary FOREIGN KEY (bowl_summary_id)
        REFERENCES bowling_summary(bowl_summary_id),
    CONSTRAINT fk_bowling_performance_match FOREIGN KEY (match_id)
        REFERENCES match(match_id),
    CONSTRAINT uq_bowling_perf_match_summary UNIQUE (match_id, bowl_summary_id),
    CONSTRAINT ck_bowling_performance_values CHECK (
        wickets_taken >= 0 AND
        balls_bowled >= 0 AND
        runs_conceded >= 0 AND
        economy_rate >= 0
    )
);

CREATE TABLE fielding_performance (
    field_stat_id     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    field_summary_id  NUMBER(10) NOT NULL,
    match_id          NUMBER(10) NOT NULL,
    catches           NUMBER(10) NOT NULL,
    stumpings         NUMBER(10) NOT NULL,
    runs_out_direct   NUMBER(10) NOT NULL,
    byes_conceded     NUMBER(10) NOT NULL,

    CONSTRAINT pk_fielding_performance PRIMARY KEY (field_stat_id),
    CONSTRAINT fk_fielding_performance_summary FOREIGN KEY (field_summary_id)
        REFERENCES fielding_summary(field_summary_id),
    CONSTRAINT fk_fielding_performance_match FOREIGN KEY (match_id)
        REFERENCES match(match_id),
    CONSTRAINT uq_fielding_perf_match_summary UNIQUE (match_id, field_summary_id),
    CONSTRAINT ck_fielding_performance_values CHECK (
        catches >= 0 AND
        stumpings >= 0 AND
        runs_out_direct >= 0 AND
        byes_conceded >= 0
    )
);

--------------------------------------------------------------------------------
-- 8. INTEGRITY / DISCIPLINARY MANAGEMENT
--------------------------------------------------------------------------------

CREATE TABLE rulebook (
    rule_id     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    clause_no   VARCHAR2(20) NOT NULL,
    category    VARCHAR2(50) NOT NULL,

    CONSTRAINT pk_rulebook PRIMARY KEY (rule_id),
    CONSTRAINT uq_rulebook_clause UNIQUE (category, clause_no)
);

CREATE TABLE complaint (
    complaint_id     NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    source_type      VARCHAR2(50) NOT NULL,
    date_received    DATE DEFAULT SYSDATE NOT NULL,
    description      VARCHAR2(2000) NOT NULL,
    misconduct_type  VARCHAR2(100),

    CONSTRAINT pk_complaint PRIMARY KEY (complaint_id)
);

CREATE TABLE case_record (
    case_id                NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    status                 VARCHAR2(30) DEFAULT 'OPEN' NOT NULL,
    involvement_type       VARCHAR2(50),
    date_opened            DATE DEFAULT SYSDATE NOT NULL,
    referral_status        VARCHAR2(20) DEFAULT 'NOT_REFERRED' NOT NULL,
    referred_to_authority  VARCHAR2(200),

    CONSTRAINT pk_case_record PRIMARY KEY (case_id),
    CONSTRAINT ck_case_status CHECK (
        status IN ('OPEN', 'UNDER_INVESTIGATION', 'REFERRED', 'CLOSED')
    ),
    CONSTRAINT ck_case_referral_status CHECK (
        referral_status IN ('NOT_REFERRED', 'REFERRED')
    ),
    CONSTRAINT ck_case_referral_consistency CHECK (
        (referral_status = 'NOT_REFERRED' AND referred_to_authority IS NULL)
        OR
        (referral_status = 'REFERRED' AND referred_to_authority IS NOT NULL)
    ),
    CONSTRAINT ck_case_referred_state CHECK (
        status <> 'REFERRED' OR referral_status = 'REFERRED'
    )
);

/*
  Project rule: ONLY PLAYER can participate in a case.
  The FK intentionally targets PLAYER, not PERSON.
*/
CREATE TABLE involves_in (
    person_id  NUMBER(10) NOT NULL,
    case_id    NUMBER(10) NOT NULL,

    CONSTRAINT pk_involves_in PRIMARY KEY (person_id, case_id),
    CONSTRAINT fk_involves_in_player FOREIGN KEY (person_id)
        REFERENCES player(person_id),
    CONSTRAINT fk_involves_in_case FOREIGN KEY (case_id)
        REFERENCES case_record(case_id)
);

CREATE TABLE investigates (
    person_id  NUMBER(10) NOT NULL,
    case_id    NUMBER(10) NOT NULL,
    admin_id   NUMBER(10) NOT NULL,

    CONSTRAINT pk_investigates PRIMARY KEY (person_id, case_id),
    CONSTRAINT fk_investigates_involvement FOREIGN KEY (person_id, case_id)
        REFERENCES involves_in(person_id, case_id),
    CONSTRAINT fk_investigates_admin FOREIGN KEY (admin_id)
        REFERENCES admin(person_id)
);

CREATE TABLE violates (
    case_id  NUMBER(10) NOT NULL,
    rule_id  NUMBER(10) NOT NULL,

    CONSTRAINT pk_violates PRIMARY KEY (case_id, rule_id),
    CONSTRAINT fk_violates_case FOREIGN KEY (case_id)
        REFERENCES case_record(case_id),
    CONSTRAINT fk_violates_rule FOREIGN KEY (rule_id)
        REFERENCES rulebook(rule_id)
);

CREATE TABLE source_of (
    case_id       NUMBER(10) NOT NULL,
    complaint_id  NUMBER(10) NOT NULL,

    CONSTRAINT pk_source_of PRIMARY KEY (case_id, complaint_id),
    CONSTRAINT fk_source_of_case FOREIGN KEY (case_id)
        REFERENCES case_record(case_id),
    CONSTRAINT fk_source_of_complaint FOREIGN KEY (complaint_id)
        REFERENCES complaint(complaint_id)
);

CREATE TABLE evidence (
    case_id         NUMBER(10) NOT NULL,
    evidence_no     NUMBER(10) NOT NULL,
    description     VARCHAR2(2000) NOT NULL,
    collected_date  DATE NOT NULL,

    CONSTRAINT pk_evidence PRIMARY KEY (case_id, evidence_no),
    CONSTRAINT fk_evidence_case FOREIGN KEY (case_id)
        REFERENCES case_record(case_id),
    CONSTRAINT ck_evidence_number CHECK (evidence_no > 0)
);

--------------------------------------------------------------------------------
-- 9. ADMIN OBSERVATION OF PLAYER IN A MATCH (TERNARY RELATIONSHIP)
--------------------------------------------------------------------------------

CREATE TABLE observes (
    admin_id          NUMBER(10) NOT NULL,
    player_id         NUMBER(10) NOT NULL,
    match_id          NUMBER(10) NOT NULL,
    observation_date  DATE NOT NULL,
    remarks           VARCHAR2(2000),

    CONSTRAINT pk_observes PRIMARY KEY
        (admin_id, player_id, match_id, observation_date),
    CONSTRAINT fk_observes_admin FOREIGN KEY (admin_id)
        REFERENCES admin(person_id),
    CONSTRAINT fk_observes_player FOREIGN KEY (player_id)
        REFERENCES player(person_id),
    CONSTRAINT fk_observes_match FOREIGN KEY (match_id)
        REFERENCES match(match_id)
);

--------------------------------------------------------------------------------
-- 10. AUDIT SUPPORT
--------------------------------------------------------------------------------

CREATE TABLE audit_log (
    audit_id           NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    actor_person_id    NUMBER(10),
    entity_name        VARCHAR2(50) NOT NULL,
    record_identifier  VARCHAR2(200) NOT NULL,
    operation          VARCHAR2(10) NOT NULL,
    action_timestamp   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    old_values         CLOB,
    new_values         CLOB,

    CONSTRAINT pk_audit_log PRIMARY KEY (audit_id),
    CONSTRAINT fk_audit_log_actor FOREIGN KEY (actor_person_id)
        REFERENCES person(person_id),
    CONSTRAINT ck_audit_operation CHECK (
        operation IN ('INSERT', 'UPDATE', 'DELETE')
    )
);

